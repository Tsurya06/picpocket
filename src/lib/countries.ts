/**
 * Detects the user's default country based on their browser timezone or locale.
 */
export function detectDefaultCountry(): Country {
  if (typeof Intl !== 'undefined') {
    try {
      const timeZone = Intl.DateTimeFormat().resolvedOptions().timeZone;
      if (timeZone) {
        if (timeZone.startsWith('Asia/Kolkata') || timeZone.startsWith('Asia/Calcutta')) {
          return COUNTRIES.find((c) => c.code === 'IN') ?? COUNTRIES[0]!;
        }
        if (timeZone.startsWith('America/')) {
          return COUNTRIES.find((c) => c.code === 'US') ?? COUNTRIES[1]!;
        }
        if (timeZone.startsWith('Europe/London')) {
          return COUNTRIES.find((c) => c.code === 'GB') ?? COUNTRIES[2]!;
        }
        if (timeZone.startsWith('Asia/Dubai')) {
          return COUNTRIES.find((c) => c.code === 'AE') ?? COUNTRIES[3]!;
        }
      }
    } catch {
      // Best effort detection.
    }
  }

  // Fallback to India (or US if locale is en-US)
  if (typeof navigator !== 'undefined' && navigator.language) {
    if (navigator.language.endsWith('-IN') || navigator.language.startsWith('hi')) {
      return COUNTRIES.find((c) => c.code === 'IN') ?? COUNTRIES[0]!;
    }
  }

  return COUNTRIES[0]!;
}

/**
 * Parses a phone number that might already include an international prefix (e.g. +91 9876543210).
 * Returns the matched country and national number if found.
 */
export function parseInternationalPhone(
  raw: string,
): { country: Country; national: string } | null {
  const trimmed = raw.trim();
  if (!trimmed.startsWith('+')) return null;

  // Try matching dial codes from longest to shortest (e.g. +880 before +8)
  const sorted = [...COUNTRIES].sort((a, b) => b.dial.length - a.dial.length);
  for (const country of sorted) {
    if (trimmed.startsWith(country.dial)) {
      const national = trimmed.slice(country.dial.length).trim();
      return { country, national };
    }
  }
  return null;
}
